import assert from 'node:assert/strict';
import {captureBackupState, cleanBackupState, restoreBackupState} from '../web/src/lib/backupState.ts';
const values = new Map();
const storage = {get length(){return values.size;}, key:index => [...values.keys()][index] ?? null, getItem:key => values.get(key) ?? null, setItem:(key,value) => values.set(key,value)};
storage.setItem('musike:cues:v1', JSON.stringify({song1:{A:{1:1.25}, J:{16:90}}}));
storage.setItem('musike:cue-bank', 'J');
storage.setItem('musike:midi:preset', 'sp404mkii-b');
storage.setItem('musike:loops',JSON.stringify({song1:{from:1,to:3,on:true}}));
storage.setItem('unrelated-token', 'must not be exported');
const exported = captureBackupState(storage);
assert.equal(exported['unrelated-token'], undefined);
values.clear();
restoreBackupState(exported, 'replace', storage);
assert.equal(JSON.parse(storage.getItem('musike:cues:v1')).song1.J[16], 90);
assert.equal(storage.getItem('musike:cue-bank'), 'J');
assert.equal(JSON.parse(storage.getItem('musike:loops')).song1.to,3);
restoreBackupState({'musike:cues:v1':JSON.stringify({song1:{A:{1:99,2:2.5}},song2:{B:{3:8}}})}, 'merge', storage);
const merged = JSON.parse(storage.getItem('musike:cues:v1'));
assert.equal(merged.song1.A[1], 1.25);
assert.equal(merged.song1.A[2], 2.5);
assert.equal(merged.song1.J[16], 90);
assert.equal(merged.song2.B[3], 8);
const before = [...values];
assert.throws(() => restoreBackupState({'musike:cue-bank':'A','musike:cues:v1':'{"bad":{"Z":{"1":-2}}}'}, 'replace', storage));
assert.deepEqual([...values], before);
assert.deepEqual(cleanBackupState({unrelated:'ignored'}), {});
console.log('PASS: cue/MIDI backup round-trip, legacy optional state, non-destructive merge and validation before writes');
